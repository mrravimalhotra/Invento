// Builds supabase/fresh-install.sql: every migration in one file, in the
// order that works on an EMPTY Supabase project, so a new database can be
// created with a single paste instead of 80+ separate runs.
//
//   node scripts/build-fresh-install.mjs
//
// Re-run it whenever a migration is added and commit the result.
//
// Order: 0001 ... 0087 by number, except 0064 (a replay-ordering repair
// for 0053) which must run straight after 0052, not in its own slot. On the
// live database 0064 was harmless; on an empty one, running it late fails.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "supabase", "migrations");
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();

const REPAIR = files.find((f) => f.startsWith("0064_"));
const AFTER = files.find((f) => f.startsWith("0052_"));
if (!REPAIR || !AFTER) throw new Error("Expected 0052_* and 0064_* migrations.");

const order = [];
for (const f of files) {
  if (f === REPAIR) continue;
  order.push(f);
  if (f === AFTER) order.push(REPAIR);
}

const last = files[files.length - 1];
let out = `-- ============================================================
-- Invento — FRESH INSTALL (all ${files.length} migrations in one file, through ${last})
--
-- FOR A NEW, EMPTY SUPABASE PROJECT ONLY. Do NOT run this on a database that
-- already has Invento data: the first migration recreates the tables.
-- An existing database only needs the newest single migrations.
--
-- How to use: Supabase -> SQL Editor -> paste this whole file -> Run.
-- Afterwards: create the first System Admin (scripts/seed-admin.ts), then
-- follow supabase/README.md for the dashboard settings that live outside SQL.
--
-- Generated by scripts/build-fresh-install.mjs — do not edit by hand.
-- ============================================================

`;
for (const f of order) {
  out += `\n-- ############################################################\n-- ## ${f}\n-- ############################################################\n\n`;
  out += readFileSync(join(dir, f), "utf8").replace(/\r\n/g, "\n").trimEnd() + "\n";
}
writeFileSync(join(root, "supabase", "fresh-install.sql"), out);
console.log(`Wrote supabase/fresh-install.sql (${order.length} migrations, ${(out.length / 1024).toFixed(0)} KB)`);
